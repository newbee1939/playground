import * as fs from 'fs';

// ABC475 B - Change  https://atcoder.jp/contests/abc475/tasks/abc475_b
//
// 【考え方】各買い物を独立に処理してよい（持っている硬貨は支払いに使わないので、
// 前の買い物が次の買い物に影響しない）。よって「1 回ぶんのお釣りの硬貨」を N 回足すだけ。
//
// 1. 出す紙幣の枚数は ceil(A/1000) 枚 = 支払額は「A 以上で最小の 1000 の倍数」。
//    お釣り = その額 - A = 「A を 1000 の倍数にするための不足分」なので
//      change = (1000 - A % 1000) % 1000
//    外側の % 1000 は A が 1000 の倍数のとき（不足分 0 なのに 1000 になる）を 0 に戻すため。
//
// 2. お釣り change (0 <= change < 1000) を最小枚数の硬貨にすると、
//    枚数はそのまま 10 進数の各桁になる（100 円 = 百の位、10 円 = 十の位、1 円 = 一の位）。
//    硬貨が 1 / 10 / 100 と「10 倍ずつ」なので大きい方から取る貪欲が最適で、
//    その貪欲はまさに 10 進表記への分解と同じ、という理屈。
//    （枚数に上限があるなど制約がもう 1 軸あると貪欲は崩れる。ここは 1 軸なので安全）
//
// 計算量 O(N)。
function main() {
  const input = fs.readFileSync(0, 'utf-8').trim().split(/\s+/);
  const n = Number(input[0]);
  const a = input.slice(1, 1 + n).map(Number);

  let coin1 = 0;
  let coin10 = 0;
  let coin100 = 0;

  for (const price of a) {
    // 例: price = 1296 のとき
    //   price % 1000 = 296          … 1000 の倍数からのはみ出しぶん
    //   1000 - 296   = 704          … 1000 の倍数にするための不足分 = お釣り
    //
    //   外側の % 1000 は price が 1000 の倍数のときだけ効く。例: price = 10000
    //     10000 % 1000 = 0  ->  1000 - 0 = 1000  …ぴったり払えるのにお釣り 1000 円になってしまう
    //     % 1000 で 0 に戻す（1000 のままだと 100 円硬貨 10 枚と数えて WA。サンプル 1 がこのケース）
    //   倍数でなければ外側の % 1000 は何もしない。例: price = 10001
    //     10001 % 1000 = 1  ->  1000 - 1 = 999  ->  999 % 1000 = 999（1000 未満なのでそのまま）
    //     11 枚（100 円 9 + 10 円 9 + 1 円 9）のお釣り。1000 円札 11 枚を出して 11000 円払う形
    const change = (1000 - (price % 1000)) % 1000;

    // change = 704 を「百の位 7 / 十の位 0 / 一の位 4」にばらす = そのまま硬貨の枚数
    //   /100 で下 2 桁を切り捨て -> 百の位        704 -> 7
    //   /10 で下 1 桁を切り捨て、%10 で百の位以上を捨てる -> 十の位   704 -> 70 -> 0
    //   %10 は 10 で割った余り = 一の位                              704 -> 4
    // change < 1000 なので /100 の側は %10 が不要（千の位が存在しない）。
    coin100 += Math.floor(change / 100);
    coin10 += Math.floor(change / 10) % 10;
    coin1 += change % 10;
  }

  console.log([coin1, coin10, coin100].join(' '));
}

main();
