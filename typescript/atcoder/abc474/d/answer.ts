import * as fs from 'fs';

// D - Outweigh
// https://atcoder.jp/contests/abc474/tasks/abc474_d
//
// ⭐️この問題は「石の重さを自分で決めていい」。高橋が勝つように決められる？ という話。
//
// ■ 1. 総和ではなく「差」だけを見る
// 石が 3 種類、A=(4,7,4)（高橋の個数）、B=(5,5,5)（青木の個数）だとする。
//   高橋の総重量 = 4×W1 + 7×W2 + 4×W3
//   青木の総重量 = 5×W1 + 5×W2 + 5×W3
// 引き算すると、同じ W ごとにまとめられる:
//   差 = (4−5)×W1 + (7−5)×W2 + (4−5)×W3
//      = (−1)×W1  +   2×W2   + (−1)×W3
// つまり効いてくるのは「種類ごとの個数の差 A_i − B_i」だけ。これを正にできるかを考える。
//
// ■ 2. No になるのはどんなとき
// 重さ W は 1 以上の正の数しか使えない。なので、個数差がすべて 0 以下だと
// どの項も（マイナス or 0）×（正）＝ 0 以下にしかならず、足しても絶対に正にならない。
//   → すべての種類で A_i ≤ B_i なら No
//
// ■ 3. Yes のときの作り方
// 逆に、A_i > B_i の種類が 1 つでもあれば、そこだけ勝っている。
// その種類の石だけ「ものすごく重い石」にして、残りは全部いちばん軽い 1 にする。
// 天秤で言えば、相手の皿に軽い小石が大量に載っていても、こちらの皿に鉛の塊を 1 つ置けば勝つ、という発想。
//   上の例では 2 種類目が勝っているので W=(1, 10^15, 1)
//   差 = (−1)×1 + 2×10^15 + (−1)×1 = 2×10^15 − 2 → 正なので Yes
//
// ■ 4. どれくらい重ければ「ものすごく重い」と言えるか
// 負けている側の合計を、いちばん悪い場合で見積もる。
//   1 種類あたりの負けは最大でも 10^9（B_i が最大 10^9、A_i が最小 1）
//   種類の数は最大 10^5
//   → 負けの合計はどう転んでも 10^9 × 10^5 = 10^14 より小さい
// 一方こちらの勝ちは、少なくとも 1 個差 × W。だから W が 10^14 より大きければ必ず勝てる。
// 10 倍の余裕をとって 10^15 にする（問題の上限 10^18 にも収まっている）。
//
// 計算量 O(N)。構築問題は「まず No の条件を言い切る → 残りで 1 つ作る」の 2 段構えで考える。

// ものすごく重い石の重さ。負けの合計（10^14 未満）を確実に上回ればよい。
// 10^15 は 2^53（JS の Number が誤差なく扱える上限 ≒ 9×10^15）より小さいので、
// BigInt を使わなくてもズレずに出力できる。
const BIG = 10 ** 15;

function main() {
  const input = fs.readFileSync(0, 'utf-8').trim().split(/\s+/);
  const n = Number(input[0]);
  const aStart = 1; // A の先頭が入力トークンの何番目か
  const bStart = 1 + n; // B の先頭

  // 高橋のほうが多く持っている種類を 1 つ探す（1 つ見つかれば十分なので即 break）
  let heavy = -1;
  for (let i = 0; i < n; i++) {
    if (Number(input[aStart + i]) > Number(input[bStart + i])) {
      heavy = i;
      break;
    }
  }

  // 1 つも勝っている種類がない ＝ どう重さを決めても勝てない
  if (heavy === -1) {
    console.log('No');
    return;
  }

  // 勝っている種類だけ極端に重く、残りは最軽量の 1
  const w = new Array<number>(n).fill(1);
  w[heavy] = BIG;
  console.log(`Yes\n${w.join(' ')}`); // 出力は 1 回にまとめる
}

main();
