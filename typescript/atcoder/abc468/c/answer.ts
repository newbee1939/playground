// 4. 辞書順の比較
// ============================================================================
/**
 * 辞書順で s < t なら true を返す（s と t は同じ長さの数列）。
 *
 * 先頭から 1 個ずつ見ていって、
 *   - 違う値に出会ったら、その大小がそのまま答え（そこで即決。残りは見ない）
 *   - 最後まで全部同じなら、s と t は同じ列 → 「小さい」ではないので false
 *
 * 例: s=(1,3,2), t=(2,1,3)
 *   i=0: 1 と 2 は違う → 1 < 2 なので true を返して終了（i=1 以降は見ない）
 *
 * 例: s=(1,3,2), t=(1,3,2)
 *   最後まで違いが無い → false（等しいので「より小さい」ではない）
 *
 * ⚠️ JavaScript の `<` を配列にそのまま使ってはいけない。
 *   [2] < [10] は、両辺が文字列 '2' と '10' に変換されて比較されるので false になる。
 *   （C++ の vector や Python の list は `<` で辞書順比較できるが、JS は別物）
 */
function isLess(s: number[], t: number[]): boolean {
  for (let i = 0; i < s.length; i++) {
    if (s[i] !== t[i]) return s[i] < t[i];
  }
  return false;
}

main();

