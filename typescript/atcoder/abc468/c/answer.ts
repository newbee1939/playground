// 5. Bonus（N <= 10^5、答えを 998244353 で割ったあまり）
// ============================================================================
// N が 10^5 だと N! 通りを作るのは当然不可能なので、発想を変えて
// 「X より辞書順で小さい順列は何個あるか」= rank(X) を直接計算する。
// 答えは rank(Q) - rank(P) - 1（P 自身のぶんを 1 引く）。
//
//   rank(X) = Σ_i （X_i より小さくて、まだ使っていない数の個数）× (N-i)!
//
// i 番目のマスで X_i より小さい数を置いた時点で、そこから先は何を置いても X より小さい。
// 残り (N-i) マスの並べ方は (N-i)! 通り、という数え方。
// 「まだ使っていない数の個数」は BIT（フェニック木）で数えられるので全体で O(N log N)。
//
// ⚠️ ただしこの式は P >= Q のとき負の数を返すので、Math.max(0, …) が必要。
//   全探索版は「条件を満たすものを数える」だけなので、この手の境界を勝手に処理してくれる。
//   N <= 10 の制約が与えられているうちは、素直に全探索するのが安全。
