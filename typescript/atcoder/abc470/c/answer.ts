// ABC470 C - Inc, Dec, Xor
// https://atcoder.jp/contests/abc470/tasks/abc470_c
//
// =============================================================================
// STEP 0. そもそも XOR (^) とは
// =============================================================================
// 2 つの数を 2 進数にして、桁ごとに「片方だけが 1 なら 1、それ以外は 0」。
//
//     2 ^ 3          5 ^ 5
//      10             101
//      11             101
//     ----           -----
//      01  = 1        000  = 0    ← 同じ数どうしは必ず 0 になる
//
// --- XOR は「反転スイッチ」。足すのと戻すのが同じ操作 ---------------------
//
// `^ 3` は「3 の 1 が立っている桁を反転しろ」という命令だと思うとよい。
//
//       5 = 1 0 1
//       3 = 0 1 1     ← 真ん中と右の桁を反転せよ、という指示
//             ↕ ↕
//   5 ^ 3 = 1 1 0 = 6
//
//       6 = 1 1 0
//       3 = 0 1 1     ← 同じ桁をもう一度反転
//             ↕ ↕
//   6 ^ 3 = 1 0 1 = 5   元に戻った
//
// 電気のスイッチと同じで、2 回押せば元通り。普通の足し算と比べると:
//
//   足し算   5 + 3 = 8  → 戻すには 8 - 3 = 5   （引き算という別の操作が必要）
//   XOR      5 ^ 3 = 6  → 戻すには 6 ^ 3 = 5   （同じ操作をもう一度でいい）
//
// つまり XOR の世界では「取り消す」＝「同じ値をもう一度 XOR する」。
// これが後で出てくる「古い値を打ち消す」の正体（自己逆元と呼ぶ）。
//
// =============================================================================
// STEP 1. 素直に解くと、なぜ間に合わないか
// =============================================================================
// 元コードは毎回この 2 つをやっていた。
//
//   ・クエリ 2 で、N 個の要素を全部見て 1 ずつ減らす        → N 回
//   ・答えを出すのに、N 個を全部 XOR し直す (reduce)        → N 回
//
// N = 50 万、Q = 50 万 なので 50万 × 50万 = 2500 億回。
// 2 秒で終わる目安は 1〜10 億回なので、数百倍オーバー。
// 書き方を工夫しても届かないので、やることを 2 つ減らす。
//
// =============================================================================
// STEP 2. 工夫 (A) 答えを毎回作り直さない → totalXor に貼っておく
// =============================================================================
// values = [2, 7] とする。全体 XOR は 2^7 = 5。
// ここで values[0] を 2 から 3 に変えたい。作り直さずに、2 手で直せる。
//
//     totalXor = 5
//     totalXor ^= 2   →  5^2 = 7    ← 古い 2 のスイッチを押して取り消す
//     totalXor ^= 3   →  7^3 = 4    ← 新しい 3 を入れる
//
// 検算: values = [3, 7] を素直に計算すると 3^7 = 4。ちゃんと一致する。
// 配列を一度も見ずに答えが更新できた。この 2 行をまとめて 1 行にしたのが
//
//     totalXor ^= 2 ^ 3;      // = totalXor ^= 古い値 ^ 新しい値
//
// --- なぜ「古い値」も要るのか（新しい値だけではダメな理由）---------------
//
// 買い物カゴで考える。りんご 100 円とみかん 200 円で合計 300 円。
// ここで「りんごを 150 円のものに取り替える」なら
//
//     300 + 150 = 450        ← りんごを 1 個 追加 したときの値。取り替えではない
//     300 - 100 + 150 = 350  ← 古いりんごを出してから新しいのを入れる。正しい
//
// 合計 300 円の中には、すでに古いりんごの 100 円が入っているから。
// XOR でも同じことが起きる。
//
//     values = [0, 1]   totalXor = 0 ^ 1 = 1   ← この 1 は values[1] の分
//
//     新しい値だけ入れる:  1 ^ 2 = 3 = (0 ^ 1) ^ 2
//                                       ~~~ 古い 1 が居座ったまま。要素 3 つ分の XOR
//     古い値も打ち消す  :  1 ^ 1 ^ 2 = 2 = (0 ^ 1) ^ 1 ^ 2 = 0 ^ 2
//                                                 ~~~~~ 1 が消えた。[0,2] の XOR
//
// totalXor は合計値であって内訳を覚えていない（1 が 0^1 なのか 3^2 なのか
// 区別できない）。だから「抜く材料」として古い値が必要になる。
//
// =============================================================================
// STEP 3. 工夫 (B) 全部見に行かない → 1 以上の「添字」だけ持つ
// =============================================================================
// クエリ 2 は「A_i >= 1 なら 1 減らす」。0 の要素には何も起きないので、
// 見に行くだけ無駄。そこで 1 以上のものが「何番地にあるか」をメモしておく。
//
//     values         = [0, 5, 0, 3]
//     nonZeroIndexes = [1, 3]    ← 5 や 3 ではなく「1 番地と 3 番地」という位置
//
// 値ではなく位置を持つ理由: 減らすには values[1]-- のように場所を指定する必要がある。
// 値 5 だけ持っていても、それがどこにあったか分からず書き換えられない。
//
// 「毎回全部なめたら結局遅いのでは？」→ 大丈夫。
// 1 個処理する = 誰かを 1 減らす = 過去にクエリ 1 で 1 増やしている。
// クエリ 1 は最大 Q 回しか来ないので、全クエリ 2 を合計しても処理は Q 回まで。
// 1 回が重いことはあっても、合計では軽い（これを「ならし計算量」と呼ぶ）。
//
// =============================================================================
// STEP 4. サンプル 1 を 1 行ずつ手で追う（N=2, Q=5）
// =============================================================================
// 入力: 1 2 / 1 2 / 1 1 / 2 / 2
//
// 初期状態   values = [0, 0]   nonZeroIndexes = []   totalXor = 0
//
// --- 1 個目「1 2」= A_2 に +1 -------------------------------------------
//   targetIndex = 2 - 1 = 1               配列は 0 始まりなので 1 番地
//   values[1] は 0 → メモに 1 を追加      nonZeroIndexes = [1]
//   totalXor ^= values[1] ^ (values[1]+1)
//            =    0       ^     1          = 1
//   values[1]++                            values = [0, 1]
//   出力 1                                 検算: 0^1 = 1  OK
//
// --- 2 個目「1 2」= A_2 に +1 -------------------------------------------
//   values[1] は 1（0 でない）→ メモはそのまま
//   totalXor = 1 ^ 1 ^ 2 = 2               古い 1 が消えて 2 が入った
//   values[1]++                            values = [0, 2]
//   出力 2                                 検算: 0^2 = 2  OK
//
// --- 3 個目「1 1」= A_1 に +1 -------------------------------------------
//   targetIndex = 0
//   values[0] は 0 → メモに 0 を追加      nonZeroIndexes = [1, 0]
//   totalXor = 2 ^ 0 ^ 1 = 3               values = [1, 2]
//   出力 3                                 検算: 1^2 = 3  OK
//
// --- 4 個目「2」= 1 以上を全部 -1 ---------------------------------------
//   nonZeroIndexes = [1, 0] の 2 箇所だけ見る（元コードは N 個全部見ていた）
//     index=1: totalXor = 3 ^ 2 ^ 1 = 0
//              values[1]-- → 1。まだ 1 以上なので残す
//     index=0: totalXor = 0 ^ 1 ^ 0 = 1
//              values[0]-- → 0。0 になったので捨てる
//   values = [0, 1]   nonZeroIndexes = [1]   totalXor = 1
//   出力 1                                 検算: 0^1 = 1  OK
//
// --- 5 個目「2」---------------------------------------------------------
//     index=1: totalXor = 1 ^ 1 ^ 0 = 0
//              values[1]-- → 0。捨てる
//   values = [0, 0]   nonZeroIndexes = []   totalXor = 0
//   出力 0                                 検算: 0^0 = 0  OK
//
// 出力は 1, 2, 3, 1, 0。サンプルと一致。
//
// =============================================================================
// おまけ: TLE とは別に元コードにあった 2 つの問題
// =============================================================================
//   ・split("") は 1 文字ずつバラすので、line[1] は「2 文字目」。
//     "1 12" が 1 と読まれてしまう（TLE 以前に WA）
//   ・console.log を Q 回呼ぶと、そのたびに OS へ書き込みを頼む処理
//     （システムコール）が走る。50 万回で数百 ms。貯めて最後に 1 回出す
//
// =============================================================================
// 余談: XOR は「ペアを消す」道具として競プロで頻出
// =============================================================================
// 「配列の中で 1 個だけ奇数回出てくる数を探せ」は、全部 XOR するだけで解ける。
// 偶数回のものはペアで打ち消し合って消え、奇数回のものだけが残るため。
//
//     [4, 1, 2, 1, 2] → 4^1^2^1^2 = 4^(1^1)^(2^2) = 4^0^0 = 4

import * as fs from 'fs';

function main() {
  // 文字列化せず Buffer（生バイト列）のまま数字を組み立てる。
  // '0' のバイト値は 48、空白は 32、改行は 10 → 「48 以上なら数字」で判定できる。
  const inputBytes = fs.readFileSync(0); // 0 は標準入力を指す番号
  let cursor = 0; // 入力のどこまで読んだか。前にしか進まない

  // 入力に書かれた数字を、頭から 1 個ずつ返す。配列の中身とは無関係
  const readNextNumber = (): number => {
    while (inputBytes[cursor] < 48) cursor++; // 空白・改行を飛ばす
    let value = 0;
    // "123" なら 1 → 12 → 123 と桁をずらしながら組み立てる
    while (cursor < inputBytes.length && inputBytes[cursor] >= 48) {
      value = value * 10 + (inputBytes[cursor++] - 48);
    }
    return value;
  };

  const n = readNextNumber(); // 数列の長さ
  const q = readNextNumber(); // クエリの個数

  // ---- 準備（→ の後ろはサンプル 1 での初期値）----

  // 数列 A 本体。整数専用の配列で初期値は全部 0 → [0, 0]
  const values = new Int32Array(n);

  // 1 以上の要素が「何番地にあるか」のメモ。中身は値ではなく添字 → []
  let nonZeroIndexes: number[] = [];

  // A 全体の XOR の現在値。毎回作り直さず、差分で直していく → 0
  let totalXor = 0;

  // 各クエリの答えを貯める箱。最後に 1 回だけまとめて出力する → []
  const answers: string[] = [];

  // 以下、各行の上のコメントはサンプル 1 の「3 個目のクエリ 1 1」と
  // 「4 個目のクエリ 2」を実行しているつもりで読むこと。
  // どちらもその直前の状態は
  //   values = [0, 2]   nonZeroIndexes = [1]   totalXor = 2

  for (let i = 0; i < q; i++) {
    // 行の先頭の数字を読む。3 個目「1 1」なら 1、4 個目「2」なら 2
    if (readNextNumber() === 1) {
      // ================= クエリ 1: A_x に +1 =================

      // 続きの「1」を読んで 1 を引く → targetIndex = 0
      //   readNextNumber() の返り値 1 … 入力に書いてある番号（問題文の A_1）
      //   targetIndex          = 0 … 配列の添字。1 引くのは配列が 0 始まりだから
      //   values[targetIndex]  = 0 … そこに入っている値
      const targetIndex = readNextNumber() - 1;

      // 今 values[0] は 0。「0 番地に中身ができる」のでメモに 0 を足す
      //   nonZeroIndexes = [1] → [1, 0]
      // すでに 1 以上ならメモ済みなので何もしない（同じ番地を二重登録しないため）
      if (values[targetIndex] === 0) nonZeroIndexes.push(targetIndex);

      // values[0] は 0 から 1 になる。この 1 行は下の 2 行をまとめたもの:
      //   totalXor ^= values[targetIndex];        古い値 0 を取り消す
      //   totalXor ^= values[targetIndex] + 1;    新しい値 1 を入れる
      // → totalXor = 2 ^ 0 ^ 1 = 3
      //   検算: 変更後の values = [1, 2] を素直に計算すると 1^2 = 3。一致
      //
      // 注意: ここに出てくる 0 と 1 は values[0] と values[1] ではなく、
      // どちらも「targetIndex 番地の 変更前 / 変更後」の値。
      // 触っていない番地の分は totalXor に入ったままなので、いじる必要がない。
      totalXor ^= values[targetIndex] ^ (values[targetIndex] + 1);

      // この時点で totalXor はもう「+1 したあとの配列」の XOR になっている。
      // 一方 values はまだ古いままなので、ここで実体を追いつかせる
      //   values = [0, 2] → [1, 2]
      // 上の計算より後にやるのは、古い値がないと差分を打ち消せないから
      values[targetIndex]++;
    } else {
      // ========= クエリ 2: 1 以上のものを全部 -1 =========
      // 直前の状態は values = [1, 2]  nonZeroIndexes = [1, 0]  totalXor = 3
      // N が 50 万でも、見に行くのはメモにある 2 箇所だけ

      // 減らしたあとも 1 以上だった番地を移す先。要らないものは移さず消える
      const stillNonZero: number[] = [];

      // index には 1, 0 の順に入る（メモに追加された順）
      for (const index of nonZeroIndexes) {
        // index=1 のとき: values[1] は 2 → 1。totalXor = 3 ^ 2 ^ 1 = 0
        // index=0 のとき: values[0] は 1 → 0。totalXor = 0 ^ 1 ^ 0 = 1
        totalXor ^= values[index] ^ (values[index] - 1);

        // index=1 → values = [1, 1] /  index=0 → values = [0, 1]
        values[index]--;

        // index=1: values[1] は 1 なので残す    stillNonZero = [1]
        // index=0: values[0] は 0 なので捨てる  stillNonZero = [1] のまま
        if (values[index] >= 1) stillNonZero.push(index);
      }

      // 作り直したメモに差し替える。nonZeroIndexes = [1, 0] → [1]
      // 次のクエリ 2 では 0 番地を見に行かなくて済む
      nonZeroIndexes = stillNonZero;
    }

    // このクエリ時点の答えを貯める。3 個目なら "3"、4 個目なら "1"
    //   answers = ["1","2"] → ["1","2","3"] → ["1","2","3","1"]
    answers.push(String(totalXor));
  }

  // 改行でつないで一気に書き出す（システムコール 1 回で済む）
  process.stdout.write(answers.join('\n') + '\n');
}

main();
